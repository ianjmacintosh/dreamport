// Regenerates the Better Auth core schema migration.
//
// Better Auth owns the shape of its `user` / `session` / `account` /
// `verification` tables; we don't hand-write that SQL. This script asks
// Better Auth's own migration builder (the same one behind `better-auth
// generate`) to compile the CREATE TABLE statements for the SQLite dialect
// D1 speaks, and writes them to a numbered migration file.
//
// The config below is only what affects the generated schema. It stays in
// sync with `src/worker/auth.ts` by staying trivial: no plugins, no extra
// `user`/`session` fields. If `createAuth` ever adds something that changes
// the schema, mirror it here (and renumber into a new migration).
//
// Run it (`npm run generate:auth-schema`) whenever `better-auth` is upgraded
// or the auth config gains a plugin/field that changes the schema, then
// review the diff like any other migration. It is not part of the build.

import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { betterAuth } from "better-auth";
import { getMigrations } from "better-auth/db/migration";

const outFile = "migrations/0001_better_auth_core_schema.sql";

// A throwaway in-memory SQLite DB: the migration builder only needs it to
// pick the SQLite dialect and compile SQL — nothing is executed against it.
const db = new DatabaseSync(":memory:");

const auth = betterAuth({
  database: db,
  // `secret` is required for construction but irrelevant to schema output.
  secret: "0".repeat(40),
});

const { compileMigrations } = await getMigrations(auth.options);
const sql = await compileMigrations();

const header = `-- Better Auth core schema (user, session, account, verification).
-- Generated by scripts/generate-auth-schema.mjs from the createAuth config.
-- Do not edit by hand: re-run the script and review the diff.
`;

writeFileSync(outFile, `${header}\n${sql.trim()}\n`);
console.log(`wrote ${outFile}`);
